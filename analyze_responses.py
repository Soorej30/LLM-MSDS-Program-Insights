#!/usr/bin/env python3
"""
LLM Audit Response Analysis Agent
Iterates through every entry in data/entries.json, sends each response to a
local Ollama model, and progressively builds an analysis in data/analysis/.

Each entry's accumulated insights are passed as context to Ollama before the
next entry is processed, so the model refines the analysis iteratively.

Usage:
    python analyze_responses.py                   # default model (llama3.2)
    python analyze_responses.py --model mistral
    python analyze_responses.py --fresh           # wipe previous analysis
    python analyze_responses.py --skip-wordcloud

Requirements:
    pip install requests wordcloud matplotlib
"""

